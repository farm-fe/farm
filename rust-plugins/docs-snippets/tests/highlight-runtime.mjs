// Input must come from the Rust react_runtime_fixture_* test, never handwritten
// compiler output. This uses the current renderer sources, not stale dist files.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const require = createRequire(path.join(root, 'packages/docs/package.json'));
const ts = require('typescript');
const React = require('react');
const { renderToString } = require('react-dom/server');
const cache = new Map();
function load(file) {
  file = path.resolve(file);
  if (cache.has(file)) return cache.get(file).exports;
  const module = { exports: {} };
  cache.set(file, module);
  const source = fs.readFileSync(file, 'utf8');
  const compiled = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX },
    reportDiagnostics: true,
  });
  assert.equal(compiled.diagnostics?.filter(value => value.category === ts.DiagnosticCategory.Error).length ?? 0, 0);
  function localRequire(specifier) {
    if (specifier === '@farmfe/docs/snippets-runtime') return load(path.join(root, 'packages/docs/src/snippets-runtime.tsx'));
    if (specifier.startsWith('.')) {
      const base = path.resolve(path.dirname(file), specifier.replace(/\.js$/, ''));
      for (const extension of ['.tsx', '.ts', '.jsx', '.js']) if (fs.existsSync(base + extension)) return load(base + extension);
      throw new Error(`Missing renderer source: ${specifier}`);
    }
    return require(specifier);
  }
  new Function('require', 'module', 'exports', compiled.outputText)(localRequire, module, module.exports);
  return module.exports;
}
const directory = process.argv[2];
assert.ok(directory, 'Pass the directory generated by the Rust fixture test');
const { CodeBlock } = load(path.join(root, 'packages/docs/src/code-block.tsx'));
const { DocsProvider } = load(path.join(root, 'packages/docs/src/client.tsx'));
const site = { basePath: '/', theme: { colorMode: 'system' } };
const page = { locale: 'en', version: 'v2' };
function render(mode, components = {}) {
  const Content = load(path.join(directory, `${mode}.jsx`)).default;
  return renderToString(React.createElement(DocsProvider, { site, page }, React.createElement(Content, {
    components: { pre: CodeBlock, ...components },
  })));
}
function canonical(html) {
  return html.replace(/style="([^"]*)"/g, (_, value) => `style="${value.split(';').filter(Boolean).sort().join(';')}"`);
}
const original = render('jsx');
const compact = render('static-html');
assert.equal(canonical(compact), canonical(original), 'SSR DOM, metadata and inline styles must remain equivalent');
assert.equal(compact.includes('<script>'), false, 'Code must never become executable markup');
assert.ok(compact.includes('&lt;script&gt;'));
assert.ok(compact.includes('data-code="&lt;/code&gt;&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;&amp; λ\n"'));
assert.ok(compact.includes('data-highlighted="true"'));
assert.ok(compact.includes('--code-light:') && compact.includes('--code-dark:'));
for (const tool of ['npm', 'pnpm', 'yarn', 'bun']) assert.ok(compact.includes(`data-command-tool="${tool}"`), tool);
const forwardingCode = props => React.createElement('code', props);
assert.equal(canonical(render('static-html', { code: forwardingCode })), canonical(render('jsx', { code: forwardingCode })));
const replacingChildren = props => React.createElement('code', { ...props, children: 'replacement' });
// The current MDX rewrite makes a compact empty fence's code slot overridable,
// while the populated JSX fence remains intrinsic. Marker snippets stay intrinsic
// in both modes. This is an explicit opt-in boundary, not arbitrary slot parity.
assert.equal(render('jsx', { code: replacingChildren }), original);
assert.throws(() => render('static-html', { code: replacingChildren }), /children|dangerouslySetInnerHTML/,
  'The compact fence code slot must forward properties, not add children');
const replacingPreChildren = props => {
  const [code] = React.Children.toArray(props.children);
  return React.createElement(CodeBlock, {
    ...props,
    children: React.cloneElement(code, { children: 'replacement' })
  });
};
assert.ok(render('jsx', { pre: replacingPreChildren }).includes('replacement'));
assert.throws(() => render('static-html', { pre: replacingPreChildren }), /children|dangerouslySetInnerHTML/,
  'A custom pre renderer replacing intrinsic token children must retain JSX mode');
