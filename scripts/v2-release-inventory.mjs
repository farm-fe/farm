export const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const digest = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
export function nativeSourceDigest(directory, entries = ['src', 'Cargo.toml', 'build.rs']) {
  const rows = [];
  function visit(file) {
    if (!fs.existsSync(file)) return;
    if (fs.lstatSync(file).isSymbolicLink()) throw new Error('Native source symlink requires review');
    if (fs.statSync(file).isDirectory()) for (const name of fs.readdirSync(file).sort()) visit(path.join(file, name));
    else {
      const bytes = fs.readFileSync(file); let content = bytes;
      try { if (!bytes.includes(0)) content = new TextDecoder('utf-8', { fatal: true }).decode(bytes).replaceAll('\r\n', '\n'); } catch {}
      rows.push([path.relative(directory, file).replaceAll('\\', '/'), crypto.createHash('sha256').update(content).digest('hex')]);
    }
  }
  for (const name of entries) visit(path.join(directory, name));
  return digest(rows);
}

