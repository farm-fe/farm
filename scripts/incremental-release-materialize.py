"""Restore published release build prerequisites without touching tracked inputs."""
# cspell:words argparse importlib
import argparse
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tarfile

def load(name,file):
    spec=importlib.util.spec_from_file_location(name,Path(__file__).with_name(file))
    value=importlib.util.module_from_spec(spec);spec.loader.exec_module(value);return value

entry=load('release_materialization_entry','incremental-release-entry.py')
proof=load('release_materialization_paths','ci-native-proof.py')
check=entry.check

def members(body):
    check(0<len(body)<=100*1024**2,'Release prerequisite archive exceeds bound')
    result={};total=0
    with tarfile.open(fileobj=io.BytesIO(body),mode='r:gz') as archive:
        rows=archive.getmembers();check(len(rows)<=20000,'Release prerequisite member count exceeds bound')
        files=[]
        for row in rows:
            if row.isdir():continue
            check(row.isfile() and row.name.startswith('package/'),'Release prerequisite special or external member rejected')
            files.append(row.name)
        proof.validate_member_set(files,'win32-x64-msvc')
        for row in rows:
            if row.isdir():continue
            total+=row.size;check(0<=row.size<=100*1024**2 and total<=200*1024**2,'Expanded release prerequisite exceeds bound')
            data=archive.extractfile(row).read(row.size+1);check(len(data)==row.size,'Incomplete release prerequisite member')
            result[row.name]=data
    return result

def write_generated(root,file,body,source_files):
    target=root/file;check(target.is_relative_to(root),'Release prerequisite destination escapes root')
    if file in source_files:
        check(source_files[file]==body,'Published prerequisite would overwrite a different tracked input');return False
    parent=root
    for part in Path(file).parts[:-1]:
        parent=parent/part;parent.mkdir(exist_ok=True)
        check(not parent.is_symlink() and not parent.is_junction() and parent.resolve(strict=True).is_relative_to(root),'Release prerequisite directory redirects')
    check(not target.is_symlink() and not target.is_junction(),'Release prerequisite final path redirects')
    if target.exists():
        check(target.is_file() and target.read_bytes()==body,'Release prerequisite would overwrite different generated bytes');return False
    with target.open('xb') as stream:stream.write(body)
    return True

def restore(source,selection,baseline,root,fetch):
    check(selection==entry.source_plan(source,baseline),'Restore plan differs from independently verified release selection')
    check(not selection['publicationBlocked'],'Release version preparation is incomplete')
    root=Path(root).resolve(strict=True)
    family=entry.chain.family_records(json.loads(source['files']['docs/releases/v2-candidate.json']))
    rebuilt=set(selection['build']);records=baseline['ledger']['packages'];restored=[]
    # Workspace public packages and only the producer host's unchanged native
    # payloads are prerequisites. Other ABI originals stay in the registry.
    for identity,row in sorted(records.items()):
        pkg=family[identity]
        if pkg['kind']!='npm' or identity in rebuilt:continue
        if pkg.get('platform') and pkg['platform']!='linux-x64-gnu':continue
        check(row['version']==pkg['version'],'Published prerequisite version differs')
        body=fetch(row)
        check(hashlib.sha256(body).hexdigest()==row['archiveSha256'],'Published prerequisite archive bytes differ')
        archive=members(body);manifest=json.loads(archive['package/package.json'].decode('utf-8'))
        check(manifest.get('name')==pkg['name'] and manifest.get('version')==pkg['version'],'Published prerequisite identity differs')
        written=[]
        if pkg.get('platform'):
            main=manifest.get('main');check(isinstance(main,str) and Path(main).name==main and '\\' not in main,'Published native main is not canonical')
            native=archive['package/'+main]
            owner=family['npm:'+pkg['owner']];directory=str(Path(owner['manifestPath']).parent).replace('\\','/')
            file='packages/core/binding/'+main if pkg['owner']=='@farmfe/core' else 'packages/create-farm/'+main if pkg['owner']=='create-farm' else directory+'/npm/linux-x64-gnu/'+main
            if write_generated(root,file,native,source['files']):written.append(file)
        else:
            directory=str(Path(pkg['manifestPath']).parent).replace('\\','/')
            for name,data in archive.items():
                relative=name[len('package/'):]
                if relative=='package.json' or relative.startswith(('licenses/','LICENSE','THIRD_PARTY_NOTICES','license-components')):continue
                file=directory+'/'+relative
                if file in source['files']:
                    # The source checkout is authoritative for existing inputs;
                    # published build outputs are restored only where absent.
                    continue
                if write_generated(root,file,data,source['files']):written.append(file)
        restored.append({'identity':identity,'version':row['version'],'archiveSha256':row['archiveSha256'],
                         'originSourceSHA':row['originSourceSHA'],'originRunId':row['originRunId'],'originAttempt':row['originAttempt'],'written':written})
    return {'schemaVersion':1,'kind':'published-release-prerequisites-not-new-builds','chain':'release','profile':'release',
            'sourceSHA':source['sha'],'sourceTree':source['tree'],'planHash':selection['planHash'],'baselineBinding':baseline['transaction'],'records':restored}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--selection',required=True);parser.add_argument('--output',required=True);args=parser.parse_args()
    transport=entry.actions_transport();source=entry.evidence.source_reader(entry.os.environ['GITHUB_SHA'])
    selection=json.loads(Path(args.selection).read_text(encoding='utf-8'))
    check(selection.get('baselineBinding') is not None,'First release builds all prerequisites independently')
    baseline=entry.published_baseline(transport,selection['baselineBinding'])
    registry=entry.evidence.registry_module.RegistryReadOnly()
    def fetch(row):
        check(isinstance(row.get('tarball'),str),'Verified original registry URL is missing')
        with registry.open(row['tarball']) as response:
            body=response.read(100*1024**2+1)
        return body
    result=restore(source,selection,baseline,Path.cwd(),fetch)
    output=Path(args.output);output.parent.mkdir(parents=True,exist_ok=True)
    with output.open('x',encoding='utf-8') as stream:json.dump(result,stream)

if __name__=='__main__':main()
