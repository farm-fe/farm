use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Farm sidebar JSON protocol, independent of executable configuration files.
#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SidebarConfig {
  pub items: Vec<SidebarConfigItem>,
  #[serde(default)]
  pub categories: BTreeMap<String, SidebarCategory>,
}

#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SidebarCategory {
  pub label: String,
  pub items: Vec<SidebarConfigItem>,
}

#[derive(Clone, Debug, Deserialize, Serialize, JsonSchema)]
#[serde(tag = "type", rename_all = "camelCase", deny_unknown_fields)]
pub enum SidebarConfigItem {
  Doc {
    id: String,
    #[serde(default)]
    label: Option<String>,
  },
  Category {
    label: String,
    items: Vec<SidebarConfigItem>,
  },
  CategoryRef {
    id: String,
  },
  Link {
    label: String,
    href: String,
  },
  Autogenerated {
    dir: String,
  },
}

pub fn sidebar_schema() -> schemars::schema::RootSchema {
  schemars::schema_for!(SidebarConfig)
}
