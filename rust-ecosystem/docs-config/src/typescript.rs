//! Build-time declarations derived from the authoritative Rust schema.
use serde_json::Value;
use std::{collections::BTreeMap, fmt};

#[derive(Debug)]
pub struct TypeGenerationError(String);
impl fmt::Display for TypeGenerationError {
  fn fmt(&self, output: &mut fmt::Formatter<'_>) -> fmt::Result {
    write!(output, "[DOCS_TYPES_SCHEMA] {}", self.0)
  }
}
impl std::error::Error for TypeGenerationError {}
type Result<T> = std::result::Result<T, TypeGenerationError>;
fn error(location: &str, message: &str) -> TypeGenerationError {
  TypeGenerationError(format!("{location}: {message}"))
}
fn identifier(name: &str) -> bool {
  let mut chars = name.chars();
  chars
    .next()
    .is_some_and(|ch| ch.is_ascii_alphabetic() || ch == '_')
    && chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
}

pub fn typescript() -> Result<String> {
  typescript_with_schemas(vec![])
}

/// Compose related wire protocols using the same strict renderer and reference table.
pub fn typescript_with_schemas(
  extra: Vec<(String, schemars::schema::RootSchema)>,
) -> Result<String> {
  let mut definitions = BTreeMap::new();
  for (name, schema) in vec![
    ("SiteConfig".to_string(), crate::schema()),
    ("PublicSiteConfig".to_string(), crate::public_schema()),
  ]
  .into_iter()
  .chain(extra)
  {
    let mut root =
      serde_json::to_value(schema).map_err(|cause| error(&name, &cause.to_string()))?;
    let root_object = root
      .as_object_mut()
      .ok_or_else(|| error(&name, "root must be an object"))?;
    if let Some(Value::Object(children)) = root_object.remove("definitions") {
      for (child, schema) in children {
        insert_definition(&mut definitions, child, schema)?;
      }
    }
    insert_definition(&mut definitions, name, root)?;
  }
  let mut output = format!(
    "// Generated by farmfe_docs_config from Rust JSON Schema. Do not edit.\n// Semantic URL, filesystem and collection checks remain authoritative in Rust.\nexport const DOCS_SCHEMA_VERSION = {} as const;\n\n",
    crate::SCHEMA_VERSION
  );
  for (name, schema) in &definitions {
    if !identifier(name) {
      return Err(error(name, "unsupported TypeScript identifier"));
    }
    output.push_str(&format!(
      "export type {name} = {};\n\n",
      render(schema, name, &definitions)?
    ));
  }
  Ok(output)
}

fn insert_definition(
  definitions: &mut BTreeMap<String, Value>,
  name: String,
  mut schema: Value,
) -> Result<()> {
  // Root schemas carry document annotations absent from an identical nested definition.
  if let Some(object) = schema.as_object_mut() {
    object.remove("$schema");
    object.remove("title");
  }
  if let Some(previous) = definitions.get(&name) {
    if previous != &schema {
      return Err(error(&name, "conflicting schema definitions"));
    }
  } else {
    definitions.insert(name, schema);
  }
  Ok(())
}

fn render(schema: &Value, location: &str, definitions: &BTreeMap<String, Value>) -> Result<String> {
  if let Some(enabled) = schema.as_bool() {
    return Ok(if enabled { "unknown" } else { "never" }.into());
  }
  let object = schema
    .as_object()
    .ok_or_else(|| error(location, "schema must be object or boolean"))?;
  for key in object.keys() {
    if ![
      "$schema",
      "$ref",
      "title",
      "description",
      "default",
      "format",
      "examples",
      "deprecated",
      "readOnly",
      "writeOnly",
      "type",
      "enum",
      "const",
      "anyOf",
      "oneOf",
      "allOf",
      "properties",
      "required",
      "additionalProperties",
      "items",
      "minimum",
      "maximum",
      "minLength",
      "maxLength",
      "pattern",
      "minItems",
      "maxItems",
      "uniqueItems",
      "minProperties",
      "maxProperties",
    ]
    .contains(&key.as_str())
    {
      return Err(error(
        location,
        &format!("unsupported schema keyword {key}"),
      ));
    }
  }
  if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
    let name = reference
      .strip_prefix("#/definitions/")
      .filter(|name| identifier(name) && definitions.contains_key(*name))
      .ok_or_else(|| error(location, "unresolved or unsupported schema reference"))?;
    return Ok(name.into());
  }
  if let Some(value) = schema.get("const") {
    return literal(value, location);
  }
  if let Some(values) = schema.get("enum").and_then(Value::as_array) {
    if values.is_empty() {
      return Ok("never".into());
    }
    return Ok(
      values
        .iter()
        .map(|value| literal(value, location))
        .collect::<Result<Vec<_>>>()?
        .join(" | "),
    );
  }
  for (keyword, separator) in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")] {
    if let Some(values) = schema.get(keyword).and_then(Value::as_array) {
      if values.is_empty() {
        return Err(error(location, "empty schema composition"));
      }
      return Ok(format!(
        "({})",
        values
          .iter()
          .map(|value| render(value, location, definitions))
          .collect::<Result<Vec<_>>>()?
          .join(separator)
      ));
    }
  }
  if let Some(types) = schema.get("type").and_then(Value::as_array) {
    return Ok(format!(
      "({})",
      types
        .iter()
        .map(|kind| render(&serde_json::json!({"type": kind}), location, definitions))
        .collect::<Result<Vec<_>>>()?
        .join(" | ")
    ));
  }
  match schema.get("type").and_then(Value::as_str) {
    Some("string") => Ok("string".into()),
    Some("boolean") => Ok("boolean".into()),
    Some("null") => Ok("null".into()),
    Some("integer" | "number") => {
      if let (Some(min), Some(max)) = (
        schema.get("minimum").and_then(Value::as_f64),
        schema.get("maximum").and_then(Value::as_f64),
      ) {
        if min == max && min.is_finite() {
          return Ok(min.to_string());
        }
      }
      Ok("number".into())
    }
    Some("array") => Ok(format!(
      "Array<{}>",
      render(
        schema
          .get("items")
          .ok_or_else(|| error(location, "array needs an item schema"))?,
        location,
        definitions
      )?
    )),
    Some("object") => {
      let mut output = String::from("{\n");
      let required = schema.get("required").and_then(Value::as_array);
      if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
        let mut properties: Vec<_> = properties.iter().collect();
        properties.sort_by(|left, right| left.0.cmp(right.0));
        for (name, property) in properties {
          let optional = if required
            .is_some_and(|required| required.iter().any(|field| field.as_str() == Some(name)))
          {
            ""
          } else {
            "?"
          };
          let name =
            serde_json::to_string(name).map_err(|cause| error(location, &cause.to_string()))?;
          output.push_str(&format!(
            "  {name}{optional}: {};\n",
            render(property, &format!("{location}.{name}"), definitions)?
          ));
        }
      }
      match schema.get("additionalProperties") {
        Some(Value::Bool(false)) => {}
        Some(additional) => output.push_str(&format!(
          "  [key: string]: {};\n",
          render(additional, location, definitions)?
        )),
        None => {
          return Err(error(
            location,
            "object must declare its additional-properties policy",
          ));
        }
      }
      output.push('}');
      Ok(output)
    }
    _ => Err(error(location, "unsupported or missing schema type")),
  }
}
fn literal(value: &Value, location: &str) -> Result<String> {
  match value {
    Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {
      serde_json::to_string(value).map_err(|cause| error(location, &cause.to_string()))
    }
    _ => Err(error(location, "object/array literals are not supported")),
  }
}
#[cfg(test)]
mod tests {
  use super::*;
  #[test]
  fn unsupported_schemas_fail_instead_of_becoming_any() {
    for schema in [
      serde_json::json!({"not": {"type": "string"}}),
      serde_json::json!({"$ref": "#/definitions/Missing"}),
      serde_json::json!({"type": "array"}),
    ] {
      assert!(render(&schema, "test", &BTreeMap::new()).is_err());
    }
  }
}
