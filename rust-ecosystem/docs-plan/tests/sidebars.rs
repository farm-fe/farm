use farmfe_docs_config::parse_config;
use farmfe_docs_plan::{prepare, verify};
use serde_json::{Value, json};
use std::fs;

fn fixture(sidebar: Value) -> tempfile::TempDir {
  let root = tempfile::tempdir().unwrap();
  fs::create_dir_all(root.path().join("docs/nested")).unwrap();
  for (file, content) in [
    ("index.md", "# Home\n"),
    ("start.md", "---\nid: getting-started\n---\n# Start\n"),
    ("nested/advanced.md", "# Advanced\n"),
  ] {
    fs::write(root.path().join("docs").join(file), content).unwrap();
  }
  fs::write(root.path().join("sidebar.json"), sidebar.to_string()).unwrap();
  root
}
fn plan(root: &std::path::Path) -> Result<farmfe_docs_plan::DocPlan, String> {
  let config = parse_config(&json!({"title":"Sidebar","url":"https://example.com","basePath":"/guide/","docs":{"collections":[{"id":"main","dir":"docs","routeBase":"/docs/","sidebar":"sidebar.json"}]}}).to_string(), root).unwrap();
  prepare(&config)
}
fn explicit() -> Value {
  json!({"items":[{"type":"doc","id":"index"},{"type":"categoryRef","id":"learn"},{"type":"link","label":"Source","href":"https://example.com/source"}],"categories":{"learn":{"label":"Learn","items":[{"type":"doc","id":"getting-started","label":"Begin"},{"type":"category","label":"Deep","items":[{"type":"doc","id":"nested/advanced"}]}]}}})
}

#[test]
fn sidebar_order_drives_navigation_without_external_links() {
  let root = fixture(explicit());
  let value = serde_json::to_value(plan(root.path()).unwrap()).unwrap();
  let sidebar = &value["sidebars"][0];
  assert_eq!(sidebar["collection"], "main");
  assert_eq!(sidebar["items"][1]["label"], "Learn");
  assert_eq!(sidebar["items"][1]["items"][0]["label"], "Begin");
  assert_eq!(
    sidebar["items"][1]["items"][0]["href"],
    "/guide/docs/start/"
  );
  let pages = value["routes"].as_array().unwrap();
  let home = &pages
    .iter()
    .find(|route| route["page"]["id"] == "index")
    .unwrap()["page"];
  let start = &pages
    .iter()
    .find(|route| route["page"]["id"] == "getting-started")
    .unwrap()["page"];
  assert_eq!(home["next"]["label"], "Begin");
  assert!(home.get("previous").is_none());
  assert_eq!(start["previous"]["href"], "/guide/docs/");
  assert_eq!(start["next"]["href"], "/guide/docs/nested/advanced/");
}

#[test]
fn autogenerated_uses_physical_directories_and_canonical_doc_ids() {
  let root = fixture(json!({"items":[{"type":"autogenerated","dir":"."}]}));
  let value = serde_json::to_value(plan(root.path()).unwrap()).unwrap();
  let items = &value["sidebars"][0]["items"];
  assert_eq!(items[0]["label"], "Home");
  assert_eq!(items[1]["label"], "nested");
  assert_eq!(items[1]["items"][0]["href"], "/guide/docs/nested/advanced/");
  assert_eq!(items[2]["id"], "getting-started");
}

#[test]
fn malformed_sidebar_fails_with_file_and_json_location() {
  let root = fixture(explicit());
  fs::write(
    root.path().join("sidebar.json"),
    "{\n\"items\": [broken]\n}",
  )
  .unwrap();
  let error = plan(root.path()).err().expect("malformed JSON must fail");
  assert!(
    error.contains("DOCS_SIDEBAR_PARSE") && error.contains("sidebar.json:2:"),
    "{error}"
  );
}

#[test]
fn invalid_sidebar_references_fail_and_recover() {
  for (sidebar, code) in [
    (
      json!({"items":[{"type":"doc","id":"missing"}]}),
      "DOCS_SIDEBAR_DOC",
    ),
    (
      json!({"items":[{"type":"doc","id":"index"},{"type":"doc","id":"index"}]}),
      "DOCS_SIDEBAR_DUPLICATE",
    ),
    (
      json!({"items":[{"type":"categoryRef","id":"missing"}]}),
      "DOCS_SIDEBAR_CATEGORY",
    ),
    (
      json!({"items":[{"type":"categoryRef","id":"a"}],"categories":{"a":{"label":"A","items":[{"type":"categoryRef","id":"b"}]},"b":{"label":"B","items":[{"type":"categoryRef","id":"a"}]}}}),
      "DOCS_SIDEBAR_CYCLE",
    ),
    (
      json!({"items":[{"type":"autogenerated","dir":"../outside"}]}),
      "DOCS_SIDEBAR_DIR",
    ),
    (
      json!({"items":[{"type":"link","label":"Bad","href":"javascript:alert(1)"}]}),
      "DOCS_SIDEBAR_LINK",
    ),
    (
      json!({"items":[{"type":"doc","id":"index","unknown":true}]}),
      "DOCS_SIDEBAR_PARSE",
    ),
  ] {
    let root = fixture(sidebar);
    let error = plan(root.path()).err().expect("invalid sidebar must fail");
    assert!(
      error.contains(code) && error.contains("sidebar.json"),
      "{code}: {error}"
    );
    fs::write(root.path().join("sidebar.json"), explicit().to_string()).unwrap();
    assert!(
      plan(root.path()).is_ok(),
      "must recover without an exception"
    );
  }
}

#[test]
fn changing_sidebar_invalidates_the_prepared_snapshot() {
  let root = fixture(explicit());
  let prepared = plan(root.path()).unwrap();
  verify(&prepared).unwrap();
  fs::write(root.path().join("sidebar.json"), "{\"items\":[]}").unwrap();
  let error = verify(&prepared).expect_err("sidebar inputs must be fingerprinted");
  assert!(
    error.contains("DOCS_SNAPSHOT_CHANGED") && error.contains("sidebar.json"),
    "{error}"
  );
}

#[test]
fn autogenerated_subdirectory_excludes_siblings_and_uses_public_urls() {
  let root = fixture(json!({"items":[{"type":"autogenerated","dir":"nested"}]}));
  let prepared = plan(root.path()).unwrap();
  let value = serde_json::to_value(&prepared).unwrap();
  assert_eq!(value["sidebars"][0]["items"].as_array().unwrap().len(), 1);
  assert_eq!(
    value["sidebars"][0]["items"][0]["href"],
    "/guide/docs/nested/advanced/"
  );
  let app = farmfe_docs_plan::application(&prepared).unwrap();
  assert!(app.contains("export const sidebars ="));
  assert!(!app.contains(&prepared.inputs[0].path));
  assert!(!app.contains("sidebar.json"));
}

#[test]
fn deeply_nested_autogenerated_directories_have_a_bounded_error() {
  let root = fixture(json!({"items":[{"type":"autogenerated","dir":"."}]}));
  let directory = root.path().join("docs").join(vec!["a"; 66].join("/"));
  fs::create_dir_all(&directory).unwrap();
  fs::write(directory.join("deep.md"), "# Deep\n").unwrap();
  let error = plan(root.path())
    .err()
    .expect("deep directory tree must fail");
  assert!(error.contains("DOCS_SIDEBAR_DEPTH"), "{error}");
}

#[test]
fn sidebar_public_links_apply_the_mount_once_before_query_or_fragment() {
  let root = fixture(
    json!({"items":[{"type":"link","label":"Home","href":"/guide?from=menu"},{"type":"link","label":"Book","href":"/guidebook#chapter"}]}),
  );
  let value = serde_json::to_value(plan(root.path()).unwrap()).unwrap();
  assert_eq!(
    value["sidebars"][0]["items"][0]["href"],
    "/guide/?from=menu"
  );
  assert_eq!(
    value["sidebars"][0]["items"][1]["href"],
    "/guide/guidebook#chapter"
  );
}

#[test]
fn fallback_sidebar_and_navigation_stay_in_each_locale_and_version() {
  let root = tempfile::tempdir().unwrap();
  let mut collections = vec![];
  for (id, locale, version, route_base) in [
    ("en-current", "en", "current", "/docs/"),
    ("zh-current", "zh", "current", "/zh/docs/"),
    ("en-old", "en", "old", "/old/docs/"),
    ("zh-old", "zh", "old", "/zh/old/docs/"),
  ] {
    fs::create_dir(root.path().join(id)).unwrap();
    fs::write(root.path().join(id).join("index.md"), "# Home\n").unwrap();
    if id != "zh-current" {
      fs::write(root.path().join(id).join("next.md"), "# Next\n").unwrap();
    }
    let mut collection = json!({"id":id,"group":"guide","locale":locale,"version":version,"dir":id,"routeBase":route_base});
    if id == "zh-current" {
      collection["fallbackLocale"] = json!("en");
    }
    collections.push(collection);
  }
  let config = parse_config(&json!({"title":"Groups","url":"https://example.com","basePath":"/guide/","locales":{"default":"en","items":["en","zh"]},"docs":{"collections":collections}}).to_string(), root.path()).unwrap();
  let prepared = prepare(&config).unwrap();
  assert_eq!(prepared.sidebars.len(), 4);
  for route in &prepared.routes {
    let sibling = route
      .page
      .next
      .as_ref()
      .or(route.page.previous.as_ref())
      .unwrap();
    let target = prepared
      .routes
      .iter()
      .find(|candidate| candidate.page.key == sibling.key)
      .unwrap();
    assert_eq!(route.page.collection, target.page.collection);
    assert_eq!(route.page.locale, target.page.locale);
    assert_eq!(route.page.version, target.page.version);
  }
  let fallback = &prepared
    .routes
    .iter()
    .find(|route| route.page.collection == "zh-current" && route.page.id == "next")
    .unwrap()
    .page;
  assert!(fallback.fallback_source.is_some());
  assert_eq!(fallback.previous.as_ref().unwrap().href, "/guide/zh/docs/");
}
