use crate::{
  hash, prepare::farm_path, routes::logical_id, DocPlan, PageNavigation, PlanInput, PublicPage,
  PublicSidebar, PublicSidebarItem,
};
use farmfe_docs_config::{ResolvedCollection, SidebarConfig, SidebarConfigItem, ValidatedConfig};
use std::{
  collections::{BTreeMap, HashMap, HashSet},
  fs,
  path::Path,
};

struct Builder<'a> {
  source: &'a str,
  config: &'a SidebarConfig,
  site: &'a ValidatedConfig,
  plan: &'a DocPlan,
  pages: HashMap<String, &'a PublicPage>,
  collection: &'a ResolvedCollection,
  seen: HashSet<String>,
  order: Vec<PageNavigation>,
  stack: Vec<String>,
}
#[derive(Default)]
struct Directory<'a> {
  index: Option<&'a PublicPage>,
  children: BTreeMap<String, Directory<'a>>,
  page: Option<&'a PublicPage>,
}
impl Builder<'_> {
  fn error(&self, code: &str, location: &str, message: impl std::fmt::Display) -> String {
    format!("[{code}] {} ({location}): {message}", self.source)
  }
  fn label(&self, value: &str, location: &str) -> Result<(), String> {
    if value.trim().is_empty() || value.chars().any(char::is_control) {
      return Err(self.error(
        "DOCS_SIDEBAR_LABEL",
        location,
        "label must be nonempty text",
      ));
    }
    Ok(())
  }
  fn doc(
    &mut self,
    page: &PublicPage,
    label: Option<&str>,
    location: &str,
  ) -> Result<PublicSidebarItem, String> {
    if !self.seen.insert(page.key.clone()) {
      return Err(self.error(
        "DOCS_SIDEBAR_DUPLICATE",
        location,
        format!("document {:?} appears more than once", page.id),
      ));
    }
    let label = label.unwrap_or(&page.title);
    self.label(label, location)?;
    self.order.push(PageNavigation {
      key: page.key.clone(),
      id: page.id.clone(),
      label: label.into(),
      href: page.route_path.clone(),
    });
    Ok(PublicSidebarItem::Doc {
      key: page.key.clone(),
      id: page.id.clone(),
      label: label.into(),
      href: page.route_path.clone(),
    })
  }
  fn directory(
    &mut self,
    directory: Directory<'_>,
    location: &str,
    depth: usize,
  ) -> Result<Vec<PublicSidebarItem>, String> {
    if depth > 64 {
      return Err(self.error(
        "DOCS_SIDEBAR_DEPTH",
        location,
        "directory nesting exceeds 64",
      ));
    }
    let mut items = vec![];
    if let Some(page) = directory.index {
      items.push(self.doc(page, None, location)?);
    }
    for (label, child) in directory.children {
      if let Some(page) = child.page {
        items.push(self.doc(page, None, location)?);
      }
      if child.index.is_some() || !child.children.is_empty() {
        items.push(PublicSidebarItem::Category {
          label,
          items: self.directory(child, location, depth + 1)?,
        });
      }
    }
    Ok(items)
  }
  fn autogenerated(&mut self, dir: &str, location: &str) -> Result<Vec<PublicSidebarItem>, String> {
    if dir.is_empty()
      || dir.starts_with('/')
      || dir.contains(['\\', ':'])
      || dir
        .split('/')
        .any(|part| part == ".." || (part.is_empty() && dir != "."))
    {
      return Err(self.error(
        "DOCS_SIDEBAR_DIR",
        location,
        "dir must be a relative directory inside the collection",
      ));
    }
    let physical = self.collection.directory.join(dir);
    let canonical = physical
      .canonicalize()
      .map_err(|error| self.error("DOCS_SIDEBAR_DIR", location, error))?;
    if !canonical.is_dir() || !canonical.starts_with(&self.collection.directory) {
      return Err(self.error(
        "DOCS_SIDEBAR_DIR",
        location,
        "directory is absent or escapes the collection",
      ));
    }
    // Fallback pages use their original source's relative file name, but target collection URLs.
    let mut tree = Directory::default();
    for (route, module) in self.plan.routes.iter().zip(&self.plan.modules) {
      if route.page.collection != self.collection.public.id {
        continue;
      }
      let source_collection = route
        .page
        .fallback_source
        .as_ref()
        .and_then(|source| {
          self
            .site
            .collections
            .iter()
            .find(|candidate| candidate.public.id == source.collection)
        })
        .unwrap_or(self.collection);
      let source_root = farm_path(&source_collection.directory)?;
      let relative = Path::new(&module.source_path)
        .strip_prefix(Path::new(&source_root))
        .map_err(|error| self.error("DOCS_SIDEBAR_DIR", location, error))?;
      let relative = match relative.strip_prefix(Path::new(if dir == "." { "" } else { dir })) {
        Ok(relative) => relative,
        Err(_) => continue,
      };
      let mut stem = relative.to_path_buf();
      stem.set_extension("");
      let relative = farm_path(&stem)?;
      let mut parts: Vec<_> = relative.split('/').collect();
      let name = parts
        .pop()
        .ok_or_else(|| self.error("DOCS_SIDEBAR_DIR", location, "empty document path"))?;
      let mut current = &mut tree;
      for part in parts {
        current = current.children.entry(part.into()).or_default();
      }
      if name == "index" {
        current.index = Some(&route.page);
      } else {
        current.children.entry(name.into()).or_default().page = Some(&route.page);
      }
    }
    self.directory(tree, location, 0)
  }
  fn items(
    &mut self,
    items: &[SidebarConfigItem],
    location: &str,
    depth: usize,
  ) -> Result<Vec<PublicSidebarItem>, String> {
    if depth > 64 {
      return Err(self.error("DOCS_SIDEBAR_DEPTH", location, "sidebar nesting exceeds 64"));
    }
    let mut output = vec![];
    for (index, item) in items.iter().enumerate() {
      let at = format!("{location}[{index}]");
      match item {
        SidebarConfigItem::Doc { id, label } => {
          let page = self.pages.get(&logical_id(id)).copied().ok_or_else(|| {
            self.error(
              "DOCS_SIDEBAR_DOC",
              &at,
              format!(
                "document {id:?} is absent from collection {}",
                self.collection.public.id
              ),
            )
          })?;
          output.push(self.doc(page, label.as_deref(), &at)?);
        }
        SidebarConfigItem::Category { label, items } => {
          self.label(label, &at)?;
          output.push(PublicSidebarItem::Category {
            label: label.clone(),
            items: self.items(items, &format!("{at}.items"), depth + 1)?,
          });
        }
        SidebarConfigItem::CategoryRef { id } => {
          if self.stack.contains(id) {
            return Err(self.error(
              "DOCS_SIDEBAR_CYCLE",
              &at,
              format!("category path {:?} -> {id}", self.stack),
            ));
          }
          let category = self.config.categories.get(id).ok_or_else(|| {
            self.error(
              "DOCS_SIDEBAR_CATEGORY",
              &at,
              format!("category {id:?} is absent"),
            )
          })?;
          self.label(&category.label, &at)?;
          self.stack.push(id.clone());
          let children = self.items(
            &category.items,
            &format!("categories.{id}.items"),
            depth + 1,
          )?;
          self.stack.pop();
          output.push(PublicSidebarItem::Category {
            label: category.label.clone(),
            items: children,
          });
        }
        SidebarConfigItem::Link { label, href } => {
          self.label(label, &at)?;
          farmfe_docs_config::public_link(href, &at)
            .map_err(|error| self.error("DOCS_SIDEBAR_LINK", &at, error))?;
          if href.starts_with('#') {
            return Err(self.error(
              "DOCS_SIDEBAR_LINK",
              &at,
              "fragment-only links have no sidebar page context; use a doc entry",
            ));
          }
          let base = &self.site.public.base_path;
          let path_end = href.find(['?', '#']).unwrap_or(href.len());
          let (path, suffix) = href.split_at(path_end);
          let href = if path == base.trim_end_matches('/') {
            format!("{base}{suffix}")
          } else if path.starts_with('/') && !path.starts_with(base) {
            format!("{base}{}{suffix}", path.trim_start_matches('/'))
          } else {
            href.clone()
          };
          output.push(PublicSidebarItem::Link {
            label: label.clone(),
            href,
          });
        }
        SidebarConfigItem::Autogenerated { dir } => output.extend(self.autogenerated(dir, &at)?),
      }
    }
    Ok(output)
  }
}

pub fn apply(config: &ValidatedConfig, plan: &mut DocPlan) -> Result<(), String> {
  let mut sidebars = vec![];
  let mut navigation = HashMap::new();
  let mut inputs = BTreeMap::new();
  for collection in &config.collections {
    if collection.public.kind != farmfe_docs_config::CollectionKind::Doc {
      continue;
    }
    let source = collection
      .sidebar
      .as_deref()
      .map(farm_path)
      .transpose()?
      .unwrap_or_else(|| format!("collection:{}:default-sidebar", collection.public.id));
    let sidebar = if let Some(path) = &collection.sidebar {
      let bytes =
        fs::read(path).map_err(|error| format!("[DOCS_SIDEBAR_READ] {source}: {error}"))?;
      let sidebar = serde_json::from_slice::<SidebarConfig>(&bytes).map_err(|error| {
        format!(
          "[DOCS_SIDEBAR_PARSE] {source}:{}:{}: {error}",
          error.line(),
          error.column()
        )
      })?;
      inputs.insert(source.clone(), hash(&bytes));
      sidebar
    } else {
      SidebarConfig {
        items: vec![SidebarConfigItem::Autogenerated { dir: ".".into() }],
        categories: BTreeMap::new(),
      }
    };
    let mut builder = Builder {
      source: &source,
      config: &sidebar,
      site: config,
      plan,
      pages: plan
        .routes
        .iter()
        .filter(|route| route.page.collection == collection.public.id)
        .map(|route| (logical_id(&route.page.id), &route.page))
        .collect(),
      collection,
      seen: HashSet::new(),
      order: vec![],
      stack: vec![],
    };
    let items = builder.items(&sidebar.items, "items", 0)?;
    for (index, page) in builder.order.iter().enumerate() {
      navigation.insert(
        page.key.clone(),
        (
          index
            .checked_sub(1)
            .map(|previous| builder.order[previous].clone()),
          builder.order.get(index + 1).cloned(),
        ),
      );
    }
    sidebars.push(PublicSidebar {
      collection: collection.public.id.clone(),
      items,
    });
  }
  for route in &mut plan.routes {
    if let Some((previous, next)) = navigation.remove(&route.page.key) {
      route.page.previous = previous;
      route.page.next = next;
    }
  }
  plan.sidebars = sidebars;
  plan.inputs.extend(
    inputs
      .into_iter()
      .map(|(path, hash)| PlanInput { path, hash }),
  );
  Ok(())
}
