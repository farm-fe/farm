//! Regenerate both native plugin declarations from the shared Rust palette schema.
use schemars::schema_for;
use std::{env, fs, path::PathBuf};
fn main() -> Result<(), Box<dyn std::error::Error>> {
  let root = PathBuf::from(env::args().nth(1).ok_or("provide repository root")?);
  let themes = serde_json::to_value(schema_for!(farmfe_syntax_highlight::ThemeName))?;
  let names = themes["enum"]
    .as_array()
    .ok_or("theme enum schema")?
    .iter()
    .map(|v| format!("'{}'", v.as_str().unwrap()))
    .collect::<Vec<_>>()
    .join(" | ");
  let colors = serde_json::to_value(schema_for!(farmfe_syntax_highlight::TokenColors))?;
  let fields = colors["properties"]
    .as_object()
    .ok_or("token schema")?
    .iter()
    .map(|(name, property)| {
      let nullable = property["type"]
        .as_array()
        .is_some_and(|types| types.iter().any(|kind| kind == "null"))
        || property["anyOf"]
          .as_array()
          .is_some_and(|types| types.iter().any(|kind| kind["type"] == "null"));
      let value = if nullable { "string | null" } else { "string" };
      format!("  {name}?: {value};\n")
    })
    .collect::<String>();
  let shared = format!(
    "// Generated by farmfe_syntax_highlight highlight_types. Do not edit.\nexport type CodeThemeName = {names};\nexport interface TokenColors {{\n{fields}}}\nexport interface TokenOverrides {{ light?: TokenColors; dark?: TokenColors; }}\nexport interface CodeThemeConfig {{ light?: CodeThemeName; dark?: CodeThemeName; tokens?: TokenOverrides; }}\nexport interface HighlightOptions extends CodeThemeConfig {{ representation?: 'jsx' | 'static-html'; }}\n"
  );
  fs::write(
    root.join("rust-plugins/syntax-highlight/scripts/index.d.ts"),
    format!(
      "{shared}export default function syntaxHighlight(options?: HighlightOptions): [string, HighlightOptions];\n"
    ),
  )?;
  fs::write(
    root.join("rust-plugins/docs-snippets/scripts/index.d.ts"),
    format!(
      "{shared}export interface DocsSnippetsOptions {{ rendererModule?: string; highlight?: HighlightOptions; }}\nexport default function snippets(options?: DocsSnippetsOptions): [string, DocsSnippetsOptions];\n"
    ),
  )?;
  Ok(())
}
