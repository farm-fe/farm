import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

/** Preserve ESM type identity while declaring the actual CommonJS values. */
export function createCjsTypes(entry, esmNames, cjsNames) {
  const names = esmNames.filter((name) => name !== '__esModule').sort();
  assert.deepEqual(
    cjsNames.filter((name) => name !== '__esModule').sort(),
    names,
    'Core ESM and CJS runtime exports must match before sharing their types'
  );
  const program = ts.createProgram([entry], {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry);
  assert(source, 'Missing normal ESM declarations');
  const module = checker.getSymbolAtLocation(source);
  assert(module, 'ESM declarations must describe an external module');
  const symbols = new Map(
    checker.getExportsOfModule(module).map((symbol) => [symbol.name, symbol])
  );
  const lines = [
    '// Generated by scripts/prepare-cjs-types.mjs; do not edit.',
    "import type * as ESM from './index.js' with { 'resolution-mode': 'import' };",
    "export type * from './index.js' with { 'resolution-mode': 'import' };"
  ];
  for (const name of names) {
    assert(
      /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && name !== 'default',
      `Review unsupported public export name: ${name}`
    );
    let symbol = symbols.get(name);
    assert(symbol, `Runtime export has no public declaration: ${name}`);
    if (symbol.flags & ts.SymbolFlags.Alias) {
      symbol = checker.getAliasedSymbol(symbol);
    }
    lines.push(`export declare const ${name}: typeof ESM.${name};`);
    if (symbol.flags & ts.SymbolFlags.Type) {
      if (name === 'RuntimeServerOwner') {
        const declaration = symbol.declarations?.find(ts.isClassDeclaration);
        const parameters = declaration?.typeParameters;
        assert(parameters?.length === 1 && parameters[0].name.text === 'T' && parameters[0].constraint?.getText() === 'OwnedRuntimeServer' && !parameters[0].default,
          'Review changed RuntimeServerOwner generic constraints before bridging');
        lines.push('export type RuntimeServerOwner<T extends ESM.OwnedRuntimeServer> = ESM.RuntimeServerOwner<T>;');
        continue;
      }
      assert(
        symbol.declarations?.every((node) => !node.typeParameters?.length),
        `Review generic public type/value export before bridging it: ${name}`
      );
      lines.push(`export type ${name} = ESM.${name};`);
    }
  }
  return lines.join('\n') + '\n';
}

export async function prepareCjsTypes() {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const esm = await import(pathToFileURL(path.join(root, 'dist/index.js')).href);
  const cjs = createRequire(import.meta.url)(path.join(root, 'dist/cjs/index.cjs'));
  const declaration = createCjsTypes(
    path.join(root, 'dist/index.d.ts'),
    Object.keys(esm),
    Object.keys(cjs)
  );
  await writeFile(path.join(root, 'dist/index.d.cts'), declaration);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await prepareCjsTypes();
}
